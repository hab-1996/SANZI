function selectStarterPrompts(previousPrompts = []) {
  const shuffledPool = [...STARTER_PROMPT_POOL]
  for (let index = shuffledPool.length - 1; index > 0; index -= 1) {
    const randomIndex = Math.floor(Math.random() * (index + 1))
    const currentPrompt = shuffledPool[index]
    shuffledPool[index] = shuffledPool[randomIndex]
    shuffledPool[randomIndex] = currentPrompt
  }

  const previousTitles = new Set(previousPrompts.map((prompt) => prompt.title))
  const selectedPrompts = shuffledPool.slice(0, 4)
  if (
    selectedPrompts.length === previousTitles.size &&
    selectedPrompts.every((prompt) => previousTitles.has(prompt.title))
  ) {
    selectedPrompts[3] = shuffledPool.find((prompt) => !previousTitles.has(prompt.title))
  }

  return selectedPrompts
}

