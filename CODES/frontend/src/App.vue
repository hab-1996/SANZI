// Send a JSON request to the local Python backend
async function api(path, options = {}) {
  // Allow slightly longer than the backend's 120-second generation limit.
  const controller = new AbortController()
  const timeout = window.setTimeout(() => controller.abort(), 135000)
  let response
  try {
    response = await fetch(path, {
      ...options,
      signal: controller.signal,
      headers: { 'Content-Type': 'application/json', ...(options.headers ?? {}) },
    })
  } catch (err) {
    if (err.name === 'AbortError') {
      throw new Error('The request took too long and was stopped. Try a smaller max length or use Qwen 0.5B.')
    }
    throw err
  } finally {
    window.clearTimeout(timeout)
  }
  let payload = {}
  try {
    payload = await response.json()
  } catch {
    // A useful fallback when the local server closes unexpectedly.
  }
  if (!response.ok) throw new Error(payload.error || `Request failed (${response.status})`)
  return payload
}

function setError(value) {
  error.value = value instanceof Error ? value.message : String(value)
  window.setTimeout(() => {
    if (error.value === (value instanceof Error ? value.message : String(value))) error.value = ''
  }, 7000)
}

async function loadState() {
  try {
    syncState(await api('/api/state'))
    followNewestMessage.value = true
    await scrollToBottom()
  } catch (err) {
    setError(`Cannot reach the Python backend. ${err.message}`)
  }
}

// Model power and configuration controls
async function togglePower() {
  if (busy.value) return
  busy.value = true
  busyLabel.value = poweredOn.value
    ? 'Releasing model memory…'
    : `Loading ${selected.value?.name ?? 'model'} (${selectedPrecisionInfo.value?.name ?? 'FP16'})…`
  error.value = ''
  try {
    const state = await api('/api/power', {
      method: 'POST',
      body: JSON.stringify({
        on: !poweredOn.value,
        model_id: selectedModel.value,
        precision: selectedPrecision.value,
      }),
    })
    syncState(state)
  } catch (err) {
    setError(err)
  } finally {
    busy.value = false
    busyLabel.value = ''
  }
}

async function choosePrecision(precisionId) {
  if (busy.value || precisionId === selectedPrecision.value) return
  const precision = precisions.value.find((item) => item.id === precisionId)
  if (!precision?.available) return
  // Restore the previous selection if the model reload fails.
  const previous = selectedPrecision.value
  selectedPrecision.value = precisionId
  if (!poweredOn.value) return

  busy.value = true
  busyLabel.value = `Reloading in ${precision.name}…`
  try {
    syncState(
      await api('/api/precision', {
        method: 'POST',
        body: JSON.stringify({ precision: precisionId }),
      }),
    )
  } catch (err) {
    selectedPrecision.value = previous
    await loadState()
    setError(err)
  } finally {
    busy.value = false
    busyLabel.value = ''
  }
}

async function chooseModel(modelId) {
  if (busy.value || modelId === selectedModel.value) return
  const previous = selectedModel.value
  selectedModel.value = modelId

  busy.value = true
  busyLabel.value = poweredOn.value
    ? `Switching to ${models.value.find((item) => item.id === modelId)?.name}…`
    : `Updating context for ${models.value.find((item) => item.id === modelId)?.name}…`
  try {
    syncState(
      await api('/api/model', {
        method: 'POST',
        body: JSON.stringify({ model_id: modelId }),
      }),
    )
  } catch (err) {
    selectedModel.value = previous
    await loadState()
    setError(err)
  } finally {
    busy.value = false
    busyLabel.value = ''
  }
}

// Chat and conversation management
async function sendMessage(prefill) {
  if (typeof prefill === 'string') message.value = prefill
  const prompt = message.value.trim()
  if (
    !prompt ||
    !poweredOn.value ||
    busy.value ||
    contextStatus.value.context_tokens >= contextStatus.value.safe_limit
  ) {
    return
  }

  // Show the pending round immediately while the serialized backend generates.
  message.value = ''
  conversation.value.push({ role: 'user', content: prompt }, { role: 'assistant', pending: true })
  busy.value = true
  busyLabel.value = 'SANZI is typing…'
  await scrollToBottom()

  try {
    const result = await api('/api/chat', {
      method: 'POST',
      body: JSON.stringify({ message: prompt, settings: settings.value }),
    })
    conversation.value = result.conversation
    contextStatus.value = result.context_status ?? contextStatus.value
  } catch (err) {
    conversation.value.splice(-2)
    message.value = prompt
    setError(err)
  } finally {
    busy.value = false
    busyLabel.value = ''
    await scrollToBottom()
    messageBox.value?.focus()
  }
}

async function continueResponse() {
  const latest = conversation.value.at(-1)
  if (
    busy.value ||
    latest?.role !== 'assistant' ||
    !['output_limit', 'time_limit', 'incomplete'].includes(latest.continuation_reason)
  ) {
    return
  }

  // Continuations extend the latest assistant card instead of adding a round.
  busy.value = true
  continuingResponse.value = true
  busyLabel.value = 'SANZI is continuing the response…'
  error.value = ''
  await scrollToBottom()

  try {
    const result = await api('/api/chat/continue', {
      method: 'POST',
      body: JSON.stringify({ settings: settings.value }),
    })
    conversation.value = result.conversation
    contextStatus.value = result.context_status ?? contextStatus.value
  } catch (err) {
    setError(err)
  } finally {
    continuingResponse.value = false
    busy.value = false
    busyLabel.value = ''
    await scrollToBottom()
    messageBox.value?.focus()
  }
}

async function useStarterPrompt(starterPrompt) {
  if (!poweredOn.value || busy.value || conversation.value.length > 0) return

  const currentMessage = message.value
  if (!currentMessage.startsWith(starterPrompt)) {
    message.value = currentMessage.trim()
      ? `${starterPrompt}${currentMessage.trimStart()}`
      : starterPrompt
  }

  await nextTick()
  const textarea = messageBox.value
  if (!textarea) return
  textarea.style.height = 'auto'
  textarea.style.height = `${Math.min(textarea.scrollHeight, 160)}px`
  textarea.focus()
  const cursorPosition = message.value.length
  textarea.setSelectionRange(cursorPosition, cursorPosition)
}

function shuffleStarterPrompts() {
  if (!poweredOn.value || busy.value || conversation.value.length > 0) return
  visibleStarterPrompts.value = selectStarterPrompts(visibleStarterPrompts.value)
}

async function clearConversation() {
  if (!conversation.value.length || busy.value) return
  try {
    syncState(await api('/api/conversation', { method: 'DELETE' }))
    followNewestMessage.value = true
    historyOpen.value = false
  } catch (err) {
    setError(err)
  }
}

async function removeRounds() {
  if (!rounds.value || busy.value) return
  try {
    syncState(
      await api('/api/conversation/remove', {
        method: 'POST',
        body: JSON.stringify({ rounds: removeCount.value }),
      }),
    )
    removeCount.value = 1
    historyOpen.value = false
  } catch (err) {
    setError(err)
  }
}

function requestRoundRemoval(messageIndex) {
  if (busy.value || removingRound.value) return
  roundToRemove.value = Math.floor(messageIndex / 2)
}

function cancelRoundRemoval() {
  if (!removingRound.value) roundToRemove.value = null
}

async function confirmRoundRemoval() {
  if (roundToRemove.value === null || busy.value || removingRound.value) return

  // Preserve the reader's scroll position when a round is removed above it.
  const roundIndex = roundToRemove.value
  const viewport = chatViewport.value
  const previousScrollTop = viewport?.scrollTop ?? 0
  const previousScrollHeight = viewport?.scrollHeight ?? 0
  const wasFollowingNewest = followNewestMessage.value
  const roundCards = viewport
    ? [...viewport.querySelectorAll(`[data-round-index="${roundIndex}"]`)]
    : []
  const viewportTop = viewport?.getBoundingClientRect().top ?? 0
  const removedAboveViewport =
    roundCards.length > 0 && roundCards.at(-1).getBoundingClientRect().bottom <= viewportTop

  removingRound.value = true
  try {
    syncState(
      await api('/api/conversation/remove-round', {
        method: 'POST',
        body: JSON.stringify({ round_index: roundIndex }),
      }),
    )
    roundToRemove.value = null
    await nextTick()

    if (viewport) {
      if (wasFollowingNewest) {
        viewport.scrollTop = viewport.scrollHeight
      } else if (removedAboveViewport) {
        const removedHeight = previousScrollHeight - viewport.scrollHeight
        viewport.scrollTop = Math.max(0, previousScrollTop - removedHeight)
      } else {
        viewport.scrollTop = previousScrollTop
      }
    }
  } catch (err) {
    setError(err)
  } finally {
    removingRound.value = false
  }
}

// Composer, scrolling, and information-popover helpers
function onComposerKeydown(event) {
  if (event.key === 'Enter' && !event.shiftKey) {
    event.preventDefault()
    sendMessage()
  }
}

function autoSize(event) {
  event.target.style.height = 'auto'
  event.target.style.height = `${Math.min(event.target.scrollHeight, 160)}px`
}

function onChatScroll() {
  const viewport = chatViewport.value
  if (!viewport) return
  const distanceFromBottom = viewport.scrollHeight - viewport.scrollTop - viewport.clientHeight
  followNewestMessage.value = distanceFromBottom <= 60
}

async function scrollToBottom() {
  await nextTick()
  if (chatViewport.value && followNewestMessage.value) {
    chatViewport.value.scrollTop = chatViewport.value.scrollHeight
  }
}

function toggleInfo(infoId) {
  openInfo.value = openInfo.value === infoId ? null : infoId
}

function closeInfo() {
  openInfo.value = null
}

function onGlobalKeydown(event) {
  if (event.key === 'Escape') closeInfo()
}

// Component lifecycle
onMounted(() => {
  // Load backend state once and close information popovers on outside clicks.
  document.addEventListener('click', closeInfo)
  document.addEventListener('keydown', onGlobalKeydown)
  loadState()
})

onBeforeUnmount(() => {
  document.removeEventListener('click', closeInfo)
  document.removeEventListener('keydown', onGlobalKeydown)
})
